const assert=require('node:assert/strict');
const {game}=require('../scripts/sim/harness.cjs');
const g=game(null,()=>.5);
g.run("const r=generateRecruit('識別役',1);registerRecruit(r);changeRecruitParty(r.members.id,true);enterDungeon();s.floor=1;s.enemy={units:[{...makeEnemy('slime',0),row:7,hp:99}]};Math.random=()=>.99;identifyEnemies();");
assert.equal(g.run('s.library.monsters.slime?.seen'),undefined);
g.run("recordLibraryEncounter(s.enemy);Math.random=()=>0;castMagic(0,'identifyfoe',0)");g.drain();
assert.equal(g.run('s.library.monsters.slime.seen'),true);
assert.equal(g.run('s.library.monsters.slime.identified'),true);
assert.equal(g.run('s.library.monsters.slime.count||0'),0);
g.run("renderLibrary();var e=$('#librarybody').children.find(x=>x.className==='library-entry'&&x.attributes['data-library-entry']==='monster-slime')");
assert.equal(g.run('e.children[0].textContent'), 'スライム');
assert.equal(g.run("$('#libraryprogress').textContent").split(' · ')[0],'モンスター 1/100','zero-kill spell identification counts');
assert.equal(g.run("e.children[1].textContent"),g.run("enemyDefinition('slime').unknown"));
assert.equal(g.run("e.children[1].className"),'library-subtext');
assert.equal(g.run('e.children.length'),3,'identified entry keeps details');
assert.equal(g.run("!e.onclick&&e.tabIndex===undefined&&!e.attributes.role&&!e.attributes['aria-haspopup']"),true,'identified entry no longer opens a detail dialog');
assert.equal(require('node:fs').readFileSync('dist/index.html','utf8').includes('id="librarydetaildialog"'),false,'detail dialog element removed');
const saved=g.run("save();localStorage.getItem('ash-v1')");
assert.equal(game(saved).run('s.library.monsters.slime.identified'),true);
g.run("s.library.monsters={slime:{count:2,firstFloor:1},wolf:{seen:true,count:0}};s.library.monsterIdentifyVersion=1;renderLibrary();var es=$('#librarybody').children.filter(x=>x.className==='library-entry');var sl=es.find(x=>x.attributes['data-library-entry']==='monster-slime'),wo=es.find(x=>x.attributes['data-library-entry']==='monster-wolf')");
assert.equal(g.run("sl.children[0].textContent"),g.run("enemyDefinition('slime').unknown"));
assert.equal(g.run('sl.children.length'),2);
assert.equal(g.run("$('#libraryprogress').textContent").split(' · ')[0],'モンスター 0/100','kills and sightings without identification do not count');
assert.equal(g.run("wo.children[0].textContent"),g.run("enemyDefinition('wolf').unknown"));
assert.equal(g.run('wo.children.length'),2);
assert.equal(g.run("wo.children[1].children.map(c=>c.textContent).join('')"),'撃破数0体');
assert.equal(g.run("sl.children[1].children.map(c=>c.textContent).join('')"),'撃破数2体');
assert.equal(g.run("es.filter(x=>x.children[0].textContent==='？？？').length"),g.run('ENEMIES.filter(d=>d.floors[0]===1).length')-2,'unseen stay ？？？');
g.run("s.library={monsters:{slime:{count:2,firstFloor:1},wolf:{seen:true,count:0}},items:{}};ensureLibrary()");
assert.equal(g.run('s.library.monsterIdentifyVersion'),1);
assert.equal(g.run('s.library.monsters.slime.identified'),true);
assert.equal(g.run('s.library.monsters.wolf.identified'),undefined);
console.log('PASS library identify: spell provenance, zero-kill reveal, seen/unknown states, reload and one-time legacy migration');
