const assert = require('node:assert/strict');
const { game } = require('../scripts/sim/harness.cjs');
const { createParty, seededRandom } = require('../scripts/sim/combat.cjs');
const read = (g, expr) => JSON.parse(g.run(`JSON.stringify(${expr})`));
function setup() {
  const g = game(null, seededRandom(96));
  createParty(g, [0, 1]); // The mage is deliberately not the first member.
  g.drain();
  g.run(`s.area='dungeon';s.enemy=null;s.pendingBoss=null;s.pendingStairs=false;s.done=false;
    s.cells.forEach(c=>{c.flag=false;c.trap=false;c.type='';c.open=false;delete c.chest});
    s.pos=27;s.dir=1;s.cells[s.pos].open=true;
    s.members[1].level=5;s.members[1].known=['flagview'];s.mp[1]=20;render()`);
  return g;
}
// Read the actual board HTML generated by render(), also verifying placement.
function shownCount(g) {
  const board = g.run("$('#board').innerHTML");
  const counts = [...board.matchAll(/<span class="flag-sight-count">(\d+)<\/span>/g)];
  if (!counts.length) return null;
  assert.equal(counts.length, 1, 'only the current cell has a count');
  const here = [...board.matchAll(/<button class="cell [^"]*\bhere\b[^]*?<\/button>/g)];
  assert.equal(here.length, 1);
  assert.match(here[0][0], /class="flag-sight-count"/);
  assert.match(here[0][0], new RegExp(`data-i="${g.run('s.pos')}"`));
  assert.match(here[0][0], /class="cell-number"/);
  assert.match(here[0][0], /class="direction-marker"/);
  return Number(counts[0][1]);
}
function hereLabel(g) {
  const board = g.run("$('#board').innerHTML");
  return board.match(/<button class="cell [^"]*\bhere\b[^>]*aria-label="([^"]*)"/)[1];
}

{
  const g = setup();
  assert.deepEqual(read(g, "magic('flagview')"), {
    id: 'flagview', name: '旗視', job: 1, level: 5, mp: 5, guaranteed: false,
    where: 'field', target: 'party', effect: 'flagcount', value: null,
    description: '町へ戻るまで、探索者マスの境界左下に周囲8マスの旗の数を表示する。',
  });
  g.run("s.members[1].known=[];s.members[1].level=4;Math.random=()=>0;learnMagic(1,4);openMagic(1)");
  assert.equal(g.run("s.members[1].known.includes('flagview')"), false, 'Lv4 cannot learn even with a successful roll');
  assert(!g.run("$('#magiclist').innerHTML").includes('data-spell="flagview"'));
  g.run('s.members[1].level=5;s.members[1].intelligence=12;s.members[1].piety=30;Math.random=()=>.4;learnMagic(1,5)');
  assert.equal(g.run("s.members[1].known.includes('flagview')"), false, 'IQ/30 boundary fails; piety does not determine mage learning');
  g.run('Math.random=()=>.399999;learnMagic(1,5);openMagic(1)');
  assert.equal(g.run("s.members[1].known.includes('flagview')"), true, 'Lv5 succeeds below IQ/30');
  assert.match(g.run("$('#magiclist').innerHTML"), /data-spell="flagview"/);
}
{
  const g = setup();
  g.run("s.members[1].known=['dumapic','identifyfoe','halito','katino'];Math.random=()=>0;ensureMagic()");
  assert.equal(g.run("s.members[1].known.includes('flagview')"), false,
    'existing Lv5 known list gets no retroactive flagview roll, even with Math.random() === 0');
  g.run('s.members[1].level=6;learnMagic(1,6)');
  assert.equal(g.run("s.members[1].known.includes('flagview')"), true, 'next level-up can learn it');
  g.run("s.members[1].known.push('mahalito');openMagic(1)");
  const ids = [...g.run("$('#magiclist').innerHTML").matchAll(/data-spell="([^"]+)"/g)].map(m => m[1]);
  for (const id of ['dumapic', 'identifyfoe', 'halito', 'katino']) {
    assert(ids.includes(id) && ids.indexOf(id) < ids.indexOf('flagview'), `${id} precedes flagview in renderMagic`);
  }
  assert.equal(ids[ids.indexOf('flagview') + 1], 'mahalito');
  assert.equal(g.run("MAGIC[MAGIC.findIndex(x=>x.id==='flagview')+1].id"), 'mahalito');
}
{
  const g = setup();
  g.run('s.mp[1]=5');
  assert.equal(g.run("castMagic(1,'flagview',null)"), true);
  assert.equal(g.run('s.mp[1]'), 0);
  g.drain();
  assert.equal(g.run("spellReason(1,magic('flagview'))"), '発動中', 'active flagview wins over MP shortage');
  assert.equal(g.run("castMagic(1,'flagview',null)"), false);
  assert.equal(g.run('s.mp[1]'), 0);
}
// Both light flags block both light spells, including when no MP remains.
for (const [id, state] of [
  ['milwa', 's.milwaSteps=30'], ['lomilwa', 's.milwaSteps=30'],
  ['milwa', 's.light=true'], ['lomilwa', 's.light=true'],
  ['watchful', 's.watchful=true'], ['teppeki', 's.teppeki=true'],
]) {
  const g = setup();
  g.run(`s.members[1].known.push('${id}');s.mp[1]=0;${state}`);
  assert.equal(g.run(`spellReason(1,magic('${id}'))`), '発動中', `${id}: ${state} at 0 MP`);
  g.run('s.ailments[1].silence=1');
  assert.equal(g.run(`spellReason(1,magic('${id}'))`), '沈黙している', 'earlier reasons retain priority');
  g.run("s.ailments[1].silence=0;s.area='town'");
  assert.equal(g.run(`spellReason(1,magic('${id}'))`), '今は使用不可');
}
{
  const g = setup();
  assert.equal(g.run('s.flagSight'), false);
  assert.equal(shownCount(g), null);
  const inactiveLabel = hereLabel(g);
  assert(!inactiveLabel.includes('旗'));
  assert.equal(g.run("castMagic(1,'flagview',null)"), true);
  assert.equal(g.run('s.flagSight'), true);
  assert.equal(g.run('s.mp[1]'), 15);
  assert.deepEqual(read(g, 'logQueue.map(e=>e.text)'), [
    g.run('NAMES[1]') + 'は旗視を唱えた。', '周囲の旗が見えるようになった。',
  ]);
  g.drain();
  assert.equal(shownCount(g), 0, 'active zero is visible');
  assert.equal(hereLabel(g), inactiveLabel + '、周囲の旗0本');
  assert.equal(g.run("spellReason(1,magic('flagview'))"), '発動中');
  assert.equal(g.run("castMagic(1,'flagview',null)"), false);
  assert.equal(g.run('s.mp[1]'), 15, 'recast does not consume MP');
  assert.deepEqual(read(g, 'activeSpellEffects()'), [{
    name: '旗視', description: '周囲8マスの旗の数を探索者マスの左下に表示する', remaining: '町へ戻るまで',
  }]);
  g.drain();
  g.run('renderActiveSpells()');
  assert.equal(g.run("$('#activespells').hidden"), false);
  assert.match(g.run("$('#activespellbody').innerHTML"), /旗視/);
  for (let n = 0; n <= 8; n++) {
    g.run(`s.cells.forEach(c=>c.flag=false);
      around(s.pos).slice(0,${n}).forEach((j,k)=>s.cells[j].flag=['power','guard','magic'][k%3]);
      s.cells[0].flag='magic';s.cells[s.pos].flag='guard';render()`);
    assert.equal(g.run('flagSightCount()'), n, 'count excludes the current and distant cells, regardless of traps');
    assert.equal(shownCount(g), n);
    assert.equal(hereLabel(g), inactiveLabel + `、周囲の旗${n}本`);
    const labels = [...g.run("$('#board').innerHTML").matchAll(/aria-label="([^"]*)"/g)].map(m => m[1]);
    assert.equal(labels.filter(label => label.includes('周囲の旗')).length, 1, 'only current cell announces the count');
  }
  for (const pos of [0, 7, 56, 63]) {
    g.run(`s.pos=${pos};s.cells.forEach(c=>c.flag='power');render()`);
    assert.equal(g.run('flagSightCount()'), 3, 'corners do not wrap');
    assert.equal(shownCount(g), 3);
  }
  g.run('s.flagSight=false;render();renderActiveSpells()');
  assert.equal(shownCount(g), null);
  assert(!hereLabel(g).includes('周囲の旗'), 'inactive label has no flag count phrase');
  assert.deepEqual(read(g, 'activeSpellEffects()'), []);
  assert.equal(g.run("$('#activespells').hidden"), true);
}
{
  const g = setup();
  g.run("castMagic(1,'flagview',null)");g.drain();
  for (const kind of ['power', 'guard', 'magic']) {
    g.run(`s.flagKind='${kind}';flag(28)`);
    assert.equal(g.run('flagSightCount()'), 1);
    assert.equal(shownCount(g), 1, 'flag() itself renders the new count');
    g.run('flag(28)');
    assert.equal(g.run('flagSightCount()'), 0);
    assert.equal(shownCount(g), 0, 'removal renders the new count');
  }
  g.run('flag(s.pos)');
  assert.equal(g.run('!!s.cells[s.pos].flag'), false, 'cannot flag the open current cell');
  g.drain();
  g.run("s.cells[26].flag='power';render();Math.random=()=>.99");
  assert.equal(shownCount(g), 1);
  g.run("move('forward')");g.drain();
  assert.equal(g.run('s.pos'), 28);
  assert.equal(shownCount(g), 0, 'movement recomputes around the new position');
}
{
  let g = setup();
  g.run("castMagic(1,'flagview',null)");g.drain();
  g.run("s.relic=true;s.cells[s.boss].type='down';s.pos=s.boss;travelFloor(2)");g.drain();
  assert.equal(g.run('s.floor'), 2);
  assert.equal(g.run('s.flagSight'), true, 'fresh floor profile keeps the effect');
  assert.equal(shownCount(g), 0);
  g.run('travelFloor(1)');g.drain();
  assert.equal(g.run('s.floor'), 1);
  assert.equal(g.run('s.flagSight'), true, 'saved floor keeps the effect');
  g.run('s.elevatorFloors=[1,2,3];travelElevator(3)');g.drain();
  assert.equal(g.run('s.floor'), 3);
  assert.equal(g.run('s.flagSight'), true, 'elevator generation keeps the effect');
  g.run('travelElevator(2)');g.drain();
  assert.equal(g.run('s.floor'), 2);
  assert.equal(g.run('s.flagSight'), true, 'saved elevator floor keeps the effect');
  g.run('descendPitfall()');g.drain();
  assert.equal(g.run('s.floor'), 3);
  assert.equal(g.run('s.flagSight'), true, 'pitfall keeps the effect');
  g = game(g.run("save();localStorage.getItem('ash-v1')"), seededRandom(97));g.drain();
  assert.equal(g.run('s.flagSight'), true, 'save/reload keeps the effect');
  g.run('enterTown()');g.drain();
  assert.equal(g.run('s.area'), 'town');
  assert.equal(g.run('s.flagSight'), false);
  assert.equal(shownCount(g), null);
  g.run('delete s.flagSight;ensureProfile()');
  assert.equal(g.run('s.flagSight'), false, 'old saves default to inactive');
}
